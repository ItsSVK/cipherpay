import { sql } from "drizzle-orm";
import { index, integer, sqliteTable, text, uniqueIndex } from "drizzle-orm/sqlite-core";

// NON-SECRET data only (see web/CLAUDE.md). No keys, and never the raw signature used to derive keys.
// Amounts are SEALED: encrypted in the admin's browser (lib/crypto/record-seal.ts) and stored as `*_ct` strings
// (format in lib/sealed-amount.ts). The server can't read them. The old plaintext columns (`amount`, `total`) stay
// only because SQLite can't drop NOT NULL without rebuilding the table, and rebuilding a table other tables reference
// would cascade-delete their rows on D1. New rows write '' there; the admin's browser seals old rows on its next
// unlock and clears the plaintext (POST /api/seal). Drop those columns once every row is sealed.
// Everything is scoped by `employer`: the admin wallet address that signed in. The API takes it from the
// session, never from the request body, so one wallet can never read or write another's records.

const createdAt = () =>
  integer("created_at", { mode: "timestamp" })
    .notNull()
    .default(sql`(unixepoch())`);

/** Saved addresses: a name and a wallet the employer pays. No amount here, amounts are entered per run. */
export const addresses = sqliteTable(
  "addresses",
  {
    id: text("id").primaryKey(), // uuid, generated by the API
    employer: text("employer").notNull(), // admin wallet address
    name: text("name").notNull(),
    wallet: text("wallet").notNull(),
    createdAt: createdAt(),
  },
  (t) => [uniqueIndex("addresses_employer_wallet").on(t.employer, t.wallet)],
);

/** A named list of who is paid what, per run. The same address can be in many payrolls, at different amounts. */
export const payrolls = sqliteTable(
  "payrolls",
  {
    id: text("id").primaryKey(), // uuid, generated by the API
    employer: text("employer").notNull(),
    name: text("name").notNull(),
    createdAt: createdAt(),
  },
  (t) => [index("payrolls_employer").on(t.employer, t.createdAt)],
);

export const payrollEntries = sqliteTable(
  "payroll_entries",
  {
    id: integer("id").primaryKey({ autoIncrement: true }),
    payrollId: text("payroll_id")
      .notNull()
      .references(() => payrolls.id, { onDelete: "cascade" }),
    // An address that is in a payroll can't be deleted until it is taken out (the API explains why, the FK is the backstop).
    addressId: text("address_id")
      .notNull()
      .references(() => addresses.id, { onDelete: "restrict" }),
    legacyAmount: text("amount").notNull(), // pre-sealing plaintext; '' once sealed
    amountCt: text("amount_ct"), // sealed amount; null only for a row not sealed yet
  },
  (t) => [uniqueIndex("payroll_entries_payroll_address").on(t.payrollId, t.addressId), index("payroll_entries_address").on(t.addressId)],
);

export const payrollRuns = sqliteTable(
  "payroll_runs",
  {
    id: text("id").primaryKey(), // uuid, generated by the API
    employer: text("employer").notNull(),
    label: text("label").notNull(),
    // The payroll this run was made from. Kept as history if the payroll is deleted later.
    payrollId: text("payroll_id").references(() => payrolls.id, { onDelete: "set null" }),
    // draft | pending_approval | approved | executing | done | failed
    status: text("status").notNull().default("done"),
    recipients: integer("recipients").notNull(),
    legacyTotal: text("total").notNull(), // pre-sealing plaintext; '' once sealed
    totalCt: text("total_ct"), // sealed total of the confirmed items, computed by the browser
    createdAt: createdAt(),
  },
  (t) => [index("payroll_runs_employer").on(t.employer, t.createdAt)],
);

export const payrollRunItems = sqliteTable(
  "payroll_run_items",
  {
    id: integer("id").primaryKey({ autoIncrement: true }),
    runId: text("run_id")
      .notNull()
      .references(() => payrollRuns.id, { onDelete: "cascade" }),
    recipient: text("recipient").notNull(), // wallet address
    name: text("name").notNull(),
    legacyAmount: text("amount").notNull(), // pre-sealing plaintext; '' once sealed
    amountCt: text("amount_ct"), // sealed amount; null only for a row not sealed yet
    // pending | proofs_ready | sent | confirmed | failed
    status: text("status").notNull().default("confirmed"),
    signature: text("signature"), // pay_employee tx signature (the auditor view and the indexer key on these)
    error: text("error"),
    createdAt: createdAt(),
  },
  (t) => [index("payroll_run_items_run").on(t.runId), index("payroll_run_items_recipient").on(t.recipient)],
);

/** Single-use sign-in challenges. Consumed when a signature is verified; expired ones are swept. */
export const authNonces = sqliteTable("auth_nonces", {
  nonce: text("nonce").primaryKey(),
  expiresAt: integer("expires_at").notNull(), // unix seconds
});

/** Sessions. We store only a SHA-256 of the cookie token, so a leaked database can't be replayed as a login. */
export const sessions = sqliteTable(
  "sessions",
  {
    id: text("id").primaryKey(), // sha-256 hex of the random token in the cookie
    address: text("address").notNull(),
    expiresAt: integer("expires_at").notNull(), // unix seconds
    createdAt: createdAt(),
  },
  (t) => [index("sessions_address").on(t.address)],
);
