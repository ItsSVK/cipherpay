use anchor_lang::prelude::*;
use anchor_lang::solana_program::program::invoke;
use anchor_spl::token_interface::{Mint, TokenAccount, TokenInterface};
use solana_zk_sdk_pod::encryption::auth_encryption::PodAeCiphertext;
use spl_token_2022_interface::extension::confidential_transfer::instruction::inner_withdraw;
use spl_token_confidential_transfer_proof_extraction::instruction::ProofLocation;

use crate::events::WithdrawConfidentialEvent;

/// Moves `amount` from the caller's confidential *available* balance back
/// into their ordinary public balance. Unlike `transfer_confidential`,
/// `amount` here is a plain, public argument -- Withdraw is the deliberate
/// disclosure point in this design (see `PRODUCT.md` §7.4 / `CLAUDE.md`'s
/// "Design decision: disclosure control, not anti-correlation"). Nothing
/// here should try to hide or pad `amount`; that's explicitly out of scope
/// for this project.
///
/// No `Vault` involved -- confidential accounts are wallet-owned, so this
/// CPI just needs `owner` as a real transaction signer, plain `invoke`.
///
/// Needs two proofs (ciphertext-commitment equality, range), generated by
/// the client beforehand -- same "program only ever verifies/references,
/// never generates" rule as `transfer_confidential`. Also mirrors
/// `transfer_confidential` in only accepting the context-state-account form
/// of `ProofLocation`, not the same-transaction instruction-offset form:
/// both proofs together don't reliably fit alongside the withdraw
/// instruction itself in one transaction, so the client submits two
/// separate `VerifyProof` transactions first (see
/// `tests/common/transfer_proof.rs`'s pattern, reused here), then this
/// instruction references both by address.
///
/// Deliberately doesn't close the two context-state accounts afterward --
/// same reasoning as `transfer_confidential`: that's a separate
/// account-lifecycle concern, not vault-specific logic.
#[derive(Accounts)]
pub struct WithdrawConfidential<'info> {
    pub owner: Signer<'info>,

    pub mint: InterfaceAccount<'info, Mint>,

    #[account(
        mut,
        token::mint = mint,
        token::authority = owner,
    )]
    pub token_account: InterfaceAccount<'info, TokenAccount>,

    /// CHECK: pre-verified `VerifyCiphertextCommitmentEquality` context-state
    /// account -- Token-2022 checks its ownership (must belong to the ZK
    /// ElGamal Proof program) and contents when the CPI below runs.
    pub equality_proof_context: UncheckedAccount<'info>,

    /// CHECK: pre-verified `VerifyBatchedRangeProofU64` context-state
    /// account. See `equality_proof_context`.
    pub range_proof_context: UncheckedAccount<'info>,

    pub token_program: Interface<'info, TokenInterface>,
}

impl<'info> WithdrawConfidential<'info> {
    fn withdraw(
        &self,
        amount: u64,
        new_decryptable_available_balance: [u8; 36],
    ) -> Result<()> {
        let ix = inner_withdraw(
            &self.token_program.key(),
            &self.token_account.key(),
            &self.mint.key(),
            amount,
            self.mint.decimals,
            &PodAeCiphertext(new_decryptable_available_balance),
            &self.owner.key(),
            &[],
            ProofLocation::ContextStateAccount(&self.equality_proof_context.key()),
            ProofLocation::ContextStateAccount(&self.range_proof_context.key()),
        )?;

        invoke(
            &ix,
            &[
                self.token_account.to_account_info(),
                self.mint.to_account_info(),
                self.equality_proof_context.to_account_info(),
                self.range_proof_context.to_account_info(),
                self.owner.to_account_info(),
            ],
        )?;

        Ok(())
    }
}

pub fn handle_withdraw_confidential(
    ctx: Context<WithdrawConfidential>,
    amount: u64,
    new_decryptable_available_balance: [u8; 36],
) -> Result<()> {
    ctx.accounts
        .withdraw(amount, new_decryptable_available_balance)?;

    emit!(WithdrawConfidentialEvent {
        owner: ctx.accounts.owner.key(),
        mint: ctx.accounts.mint.key(),
        token_account: ctx.accounts.token_account.key(),
        amount,
    });

    Ok(())
}
