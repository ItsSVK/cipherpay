use anchor_lang::prelude::*;
use anchor_lang::solana_program::program::invoke;
use anchor_spl::token_interface::{Mint, TokenAccount, TokenInterface};
use solana_zk_sdk_pod::encryption::{auth_encryption::PodAeCiphertext, elgamal::PodElGamalCiphertext};
use spl_token_2022_interface::extension::confidential_transfer::instruction::inner_transfer;
use spl_token_confidential_transfer_proof_extraction::instruction::ProofLocation;

use crate::events::TransferConfidentialEvent;

/// The P2P confidential send: moves `amount` (never revealed on-chain) from
/// the caller's available confidential balance into the recipient's pending
/// confidential balance. No `Vault` involved -- confidential accounts are
/// wallet-owned (see `create_confidential_account`), so this CPI just needs
/// `sender` as a real transaction signer, not a PDA.
///
/// Needs three proofs (equality, ciphertext-validity, range), generated by
/// the client beforehand -- this project's established rule that the
/// program only ever verifies/references proofs, never generates them (see
/// `CLAUDE.md`). Unlike `create_confidential_account`'s single small
/// `VerifyPubkeyValidity` proof, these three don't fit in the same
/// transaction as the transfer itself, so this instruction only accepts the
/// **context-state account** form of `ProofLocation`: the client submits
/// three separate `VerifyProof` transactions first (each creating and
/// populating a context-state account owned by the ZK ElGamal Proof
/// program), then this instruction references all three by address.
/// Token-2022 does the actual cross-checking of those contexts against the
/// ciphertexts passed here when the CPI below runs -- this instruction does
/// no proof-related validation of its own, same as every other
/// proof-consuming instruction in this project.
///
/// Deliberately doesn't close the three context-state accounts afterward --
/// that's a separate account-lifecycle concern the client can handle with a
/// plain `CloseContextState` instruction against the ZK ElGamal Proof
/// program directly; no vault-specific logic is needed for it.
#[derive(Accounts)]
pub struct TransferConfidential<'info> {
    pub sender: Signer<'info>,

    pub mint: InterfaceAccount<'info, Mint>,

    #[account(
        mut,
        token::mint = mint,
        token::authority = sender,
    )]
    pub source_token_account: InterfaceAccount<'info, TokenAccount>,

    #[account(mut, token::mint = mint)]
    pub destination_token_account: InterfaceAccount<'info, TokenAccount>,

    /// CHECK: pre-verified `VerifyCiphertextCommitmentEquality` context-state
    /// account -- Token-2022 checks its ownership (must belong to the ZK
    /// ElGamal Proof program) and contents when the CPI below runs.
    pub equality_proof_context: UncheckedAccount<'info>,

    /// CHECK: pre-verified `VerifyBatchedGroupedCiphertext3HandlesValidity`
    /// context-state account. See `equality_proof_context`.
    pub ciphertext_validity_proof_context: UncheckedAccount<'info>,

    /// CHECK: pre-verified `VerifyBatchedRangeProofU128` context-state
    /// account. See `equality_proof_context`.
    pub range_proof_context: UncheckedAccount<'info>,

    pub token_program: Interface<'info, TokenInterface>,
}

impl<'info> TransferConfidential<'info> {
    fn transfer(
        &self,
        new_source_decryptable_available_balance: [u8; 36],
        transfer_amount_auditor_ciphertext_lo: [u8; 64],
        transfer_amount_auditor_ciphertext_hi: [u8; 64],
    ) -> Result<()> {
        let ix = inner_transfer(
            &self.token_program.key(),
            &self.source_token_account.key(),
            &self.mint.key(),
            &self.destination_token_account.key(),
            &PodAeCiphertext(new_source_decryptable_available_balance),
            &PodElGamalCiphertext(transfer_amount_auditor_ciphertext_lo),
            &PodElGamalCiphertext(transfer_amount_auditor_ciphertext_hi),
            &self.sender.key(),
            &[],
            ProofLocation::ContextStateAccount(&self.equality_proof_context.key()),
            ProofLocation::ContextStateAccount(&self.ciphertext_validity_proof_context.key()),
            ProofLocation::ContextStateAccount(&self.range_proof_context.key()),
        )?;

        invoke(
            &ix,
            &[
                self.source_token_account.to_account_info(),
                self.mint.to_account_info(),
                self.destination_token_account.to_account_info(),
                self.equality_proof_context.to_account_info(),
                self.ciphertext_validity_proof_context.to_account_info(),
                self.range_proof_context.to_account_info(),
                self.sender.to_account_info(),
            ],
        )?;

        Ok(())
    }
}

pub fn handle_transfer_confidential(
    ctx: Context<TransferConfidential>,
    new_source_decryptable_available_balance: [u8; 36],
    transfer_amount_auditor_ciphertext_lo: [u8; 64],
    transfer_amount_auditor_ciphertext_hi: [u8; 64],
) -> Result<()> {
    ctx.accounts.transfer(
        new_source_decryptable_available_balance,
        transfer_amount_auditor_ciphertext_lo,
        transfer_amount_auditor_ciphertext_hi,
    )?;

    emit!(TransferConfidentialEvent {
        sender: ctx.accounts.sender.key(),
        mint: ctx.accounts.mint.key(),
        source_token_account: ctx.accounts.source_token_account.key(),
        destination_token_account: ctx.accounts.destination_token_account.key(),
    });

    Ok(())
}
